/**
 * ============================================================
 *  本地音乐歌单
 * ============================================================
 *  用法：
 *    1. 把 mp3 / m4a 文件丢进 public/music/
 *    2. 在下面 tracks 里加一行：
 *         { title: "歌名", artist: "谁", src: "/music/文件名.mp3" }
 *    3. 保存，刷新页面。首页左下角的播放器就能用。
 *
 *  tracks 是空的时候，播放器会显示「还没有歌」，
 *  按钮是灰的，不会报错。
 *
 *  注意：文件名别用中文和空格，用英文或拼音，省得路径出问题。
 *        比如 夜的钢琴曲.mp3 → ye-de-gangqin.mp3
 * ============================================================
 */

